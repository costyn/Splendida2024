#!/usr/bin/env python3
"""Generate src/geometry.h: polar/cartesian coordinates for every LED.

The Splendida PCB places its 256 LEDs on a Vogel (sunflower) spiral:
seed n sits at radius sqrt(n) and angle n * golden_angle. This script
fits that model to ldirko's 20x20 planar lookup table (to recover the
rotation/mirroring of the board) and then emits exact per-LED tables,
indexed by *physical* LED number, in the same display orientation that
XY_fibon_PLANAR() uses (LED 12 at the bottom, y grows downward).

Usage: python3 tools/gen_geometry.py > src/geometry.h
"""
import math
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = (ROOT / "src" / "tables.h").read_text()
GOLDEN_ANGLE = math.pi * (3 - math.sqrt(5))
N = 256


def table(name):
    body = re.search(name + r"\[\][^{]*\{(.*?)\};", SRC, re.S).group(1)
    body = re.sub(r"//[^\n]*", "", body)
    return [int(v) for v in re.findall(r"\d+", body)]


planar = table("FibonPlanarTable")  # 20x20, raw (unrotated) orientation
fib_to_phys = table("fibonacciToPhysical")
phys_to_fib = [0] * N
for f, p in enumerate(fib_to_phys):
    phys_to_fib[p] = f

# Grid cell of each physical LED in *display* coordinates. XY_fibon_PLANAR(x, y)
# reads raw cell (row = 19 - x, col = y), so x = 19 - row, y = col.
grid = {}
for i, p in enumerate(planar):
    if p < N:
        row, col = divmod(i, 20)
        grid[p] = (19 - row, col)


def model(f, mirror, rot):
    r = math.sqrt(f + 0.5)
    th = mirror * f * GOLDEN_ANGLE + rot
    return r * math.cos(th), r * math.sin(th)


def fit(mirror, rot):
    # least squares for x = s*mx + cx, y = s*my + cy (shared scale)
    pts = [(model(phys_to_fib[p], mirror, rot), g) for p, g in grid.items()]
    n = len(pts)
    mx = sum(m[0] for m, _ in pts) / n
    my = sum(m[1] for m, _ in pts) / n
    gx = sum(g[0] for _, g in pts) / n
    gy = sum(g[1] for _, g in pts) / n
    num = sum((m[0] - mx) * (g[0] - gx) + (m[1] - my) * (g[1] - gy) for m, g in pts)
    den = sum((m[0] - mx) ** 2 + (m[1] - my) ** 2 for m, _ in pts)
    s = num / den
    cx, cy = gx - s * mx, gy - s * my
    err = sum((s * m[0] + cx - g[0]) ** 2 + (s * m[1] + cy - g[1]) ** 2 for m, g in pts)
    return math.sqrt(err / n), s, cx, cy


best = min(
    (fit(mirror, rot) + (mirror, rot))
    for mirror in (1, -1)
    for rot in (k * 2 * math.pi / 7200 for k in range(7200))
)
rms, _, _, _, mirror, rot = best
if rms > 0.5:
    sys.exit(f"model does not fit the planar table (rms {rms:.2f} cells)")

# Exact positions from the model: unit disc, y down, centre at origin.
rmax = math.sqrt(N - 1 + 0.5)
xs, ys, angles, radii = [], [], [], []
for p in range(N):
    x, y = model(phys_to_fib[p], mirror, rot)
    x, y = x / rmax, y / rmax
    xs.append(x)
    ys.append(y)
    # angle 0 = straight up, increasing clockwise on screen
    angles.append(math.atan2(x, -y) % (2 * math.pi))
    radii.append(math.hypot(x, y))

bottom = max(range(N), key=lambda p: ys[p] - abs(xs[p]))


def q8(v):
    return max(0, min(255, int(round(v))))


def emit(name, values, ctype="uint8_t"):
    lines = []
    for i in range(0, N, 16):
        lines.append("    " + ", ".join(f"{v:3d}" for v in values[i : i + 16]) + ",")
    return f"const {ctype} {name}[NUM_LEDS] PROGMEM = {{\n" + "\n".join(lines) + "\n};\n"


chirality = "clockwise" if mirror == -1 else "counter-clockwise"
out = f"""// GENERATED by tools/gen_geometry.py - do not edit by hand.
//
// Per-LED geometry of the Fibonacci/Vogel spiral board, indexed by PHYSICAL
// LED number (the index you write into a CRGB buffer). Fitted to the planar
// lookup table with an RMS error of {rms:.2f} grid cells per LED (grid rounding
// alone gives 0.41), and checked against the PCB's own pixelblaze-map.json
// from github.com/wokwi/splendida. Orientation matches XY_fibon_PLANAR(): y grows
// downward and LED {bottom} is the bottom-most outer LED.
//
//   ledX / ledY   0..255, centre of the disc = 128,128
//   ledAngle      0..255 = one full turn; 0 = up, increasing clockwise
//   ledRadius     0 at the centre seed .. 255 at the outermost seed
//   ledRank       position in seed order (0 = centre .. 255 = edge).
//                 Seed n sits at n * golden angle, so (ledRank % F) for a
//                 Fibonacci number F (8, 13, 21, 34, 55) numbers the visible
//                 spiral arms of that family. Families alternate direction.

#ifndef GEOMETRY_H
#define GEOMETRY_H

#include <Arduino.h>

#ifndef NUM_LEDS
#define NUM_LEDS 256
#endif

"""
out += emit("ledX", [q8(128 + x * 127) for x in xs])
out += "\n" + emit("ledY", [q8(128 + y * 127) for y in ys])
out += "\n" + emit("ledAngle", [int(a / (2 * math.pi) * 256) & 255 for a in angles])
out += "\n" + emit("ledRadius", [q8(r * 255) for r in radii])
out += "\n" + emit("ledRank", phys_to_fib)
out += "\n#endif // GEOMETRY_H\n"
sys.stdout.write(out)
print(f"fit rms={rms:.3f} mirror={mirror} rot={math.degrees(rot):.2f} bottom LED={bottom} seeds wind {chirality}", file=sys.stderr)
